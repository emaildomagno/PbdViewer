export class PCodeParser105 extends PCodeParser100 {
    getPCodeLenArray() { return PCODE_LEN; }

    constructor(pbFunction) {
        super(pbFunction);
    }

    onParsePcode(pCodeOp, codeLine) {
        if (pCodeOp >= 2 && pCodeOp <= 549) return super.onParsePcode(pCodeOp - 1, codeLine);
        switch (pCodeOp) {
            case 0: this.doReturn(0); break;
            case 1: this.doReturn(BH.getUShort(codeLine.pCodeParam, 0)); break;
            default: return false;
        }
        return true;
    }
}
